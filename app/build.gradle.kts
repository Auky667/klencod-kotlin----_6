val rootDirLayout = rootProject.layout.projectDirectory
val ensureDebugKeystore =
  tasks.register("ensureDebugKeystore") {
    val keystoreFile = rootDirLayout.file("debug.keystore").asFile
    val base64File = rootDirLayout.file("debug.keystore.base64").asFile
    onlyIf { !keystoreFile.exists() }
    doLast {
      if (base64File.exists()) {
        val decoded = Base64.getMimeDecoder().decode(base64File.readText(Charsets.UTF_8))
        keystoreFile.writeBytes(decoded)
      } else {
        val javaHomeBin = File(System.getProperty("java.home"), "bin")
        val keytoolExe =
          listOf(File(javaHomeBin, "keytool"), File(javaHomeBin, "keytool.exe"))
            .firstOrNull { it.exists() }
            ?.absolutePath ?: "keytool"
        val exitCode =
          ProcessBuilder(
              keytoolExe,
              "-genkeypair",
              "-v",
              "-keystore",
              keystoreFile.absolutePath,
              "-storetype",
              "PKCS12",
              "-storepass",
              "android",
              "-alias",
              "androiddebugkey",
              "-keypass",
              "android",
              "-keyalg",
              "RSA",
              "-keysize",
              "2048",
              "-validity",
              "10000",
              "-dname",
              "CN=Android Debug,O=Android,C=US",
            )
            .redirectErrorStream(true)
            .start()
            .waitFor()
        if (exitCode != 0 || !keystoreFile.exists()) {
          throw GradleException("Failed to generate debug.keystore via keytool (exitCode=$exitCode)")
        }
      }
    }
  }

tasks
  .matching { it.name == "validateSigningDebug" || it.name == "preDebugBuild" }
  .configureEach { dependsOn(ensureDebugKeystore) }

